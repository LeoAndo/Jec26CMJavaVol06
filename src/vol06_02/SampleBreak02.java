package vol06_02;

public class SampleBreak02 {
    public static void main(String[] args) {
        int i = 2;
        switch (i) {
            case 1:
                System.out.println("iは1です。");
                break;
            case 2:
                System.out.println("iは2です。");
                break;
            default:
                System.out.println("iは3です。");
                break;
        }
    }
}
