public class SampleSwitchBreak01 {
    public static void main(String[] args) {
        int x = 1;
        // int x = 2;
        // int x = 3;
        switch (x) {
            case 1:
                System.out.println("One");
                break;
            case 2:
                System.out.println("Two");
            case 3:
                System.out.println("Three");
        }
    }
}
